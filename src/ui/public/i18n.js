  function valid(value) { return value === 'en' || value === 'ko'; }
  let current = 'en';
  try { const stored = localStorage.getItem(storageKey); if (valid(stored)) current = stored; } catch { /* Storage may be disabled. */ }
  const listeners = new Set();
  function t(key, params = {}) {
    const pair = copy[key];
    if (!pair) throw new Error(`Missing translation: ${key}`);
    return pair[current === 'ko' ? 1 : 0].replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_, name) => String(params[name] ?? ''));
  }
  function status(value) { return copy[`status.${value}`] ? t(`status.${value}`) : String(value ?? ''); }
  function artifact(value) { return copy[`artifact.${value}`] ? t(`artifact.${value}`) : String(value ?? ''); }
  function applyStatic() {
    document.documentElement.lang = current;
    document.querySelectorAll('[data-i18n]').forEach((node) => { node.textContent = t(node.dataset.i18n); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => { node.placeholder = t(node.dataset.i18nPlaceholder); });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((node) => { node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel)); });
    const select = document.getElementById('language-select');
    if (select) select.value = current;
  }
  function change(next, persist) {
    if (!valid(next) || next === current) return;
    current = next;
    if (persist) { try { localStorage.setItem(storageKey, next); } catch { /* Selection still works in this tab. */ } }
    applyStatic();
    for (const listener of listeners) listener(next);
  }
  window.addEventListener('storage', (event) => {
    if (event.key !== storageKey) return;
    change(valid(event.newValue) ? event.newValue : 'en', false);
  });
  document.documentElement.lang = current;
  window.FlowQAI18n = Object.freeze({ locale: () => current, t, status, artifact, applyStatic, setLocale: (next) => change(next, true), onChange: (listener) => { listeners.add(listener); return () => listeners.delete(listener); }, storageKey });

import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { startDemo } from '../examples/demo/server.ts';
import { startUIServer } from '../src/ui/server.ts';
import { initWorkspace, writeJSON } from '../src/workspace.ts';

const workspace = await mkdtemp(path.join(tmpdir(), 'flowqa-i18n-'));
const artifacts = path.resolve('output/playwright/i18n');
await mkdir(artifacts, { recursive: true });
let demo; let ui; let browser;
try {
  await initWorkspace(workspace);
  demo = await startDemo(0);
  await writeJSON(path.join(workspace, 'flowqa.config.json'), {
    schemaVersion: 'flow-qa/config-1', targets: { demo: { url: demo.url, description: 'Local demo · 임의 사용자 설명' } },
    timeoutMs: 15_000, retries: 0,
  });
  ui = await startUIServer({ workspace, port: 0 });
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'ko-KR', colorScheme: 'light' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const hasBeforeUnloadWarning = () => page.evaluate(() => {
    const event = new Event('beforeunload', { cancelable: true });
    window.dispatchEvent(event);
    return event.defaultPrevented;
  });
  const downloadCaseFile = async (selector) => {
    const event = page.waitForEvent('download');
    await page.locator(selector).click();
    const file = await event;
    return { name: file.suggestedFilename(), text: await readFile(await file.path(), 'utf8') };
  };
  await page.goto(ui.url);
  await page.waitForFunction(() => document.querySelector('#connection-label').textContent.includes('connected'));
  assert.equal(await page.locator('html').getAttribute('lang'), 'en', 'First visit defaults to English even in a Korean browser.');
  assert.equal(await hasBeforeUnloadWarning(), false, 'An empty draft does not warn before leaving.');
  assert.equal(await page.locator('#suite-download').isEnabled(), false);
  assert.equal(await page.locator('#flow-download').isEnabled(), false);
  const cleanReloadDialogs = [];
  const trackCleanReloadDialog = dialog => { cleanReloadDialogs.push(dialog.type()); void dialog.dismiss(); };
  page.on('dialog', trackCleanReloadDialog);
  await page.reload();
  page.off('dialog', trackCleanReloadDialog);
  assert.deepEqual(cleanReloadDialogs, [], 'A clean reload does not show a browser prompt.');
  await page.waitForFunction(() => document.querySelector('#connection-label').textContent.includes('connected'));
  await page.locator('#flow-input').click();
  await page.locator('#flow-input').fill('Keep this unsaved flow');
  assert.equal(await hasBeforeUnloadWarning(), true, 'Typed flow content warns before leaving.');
  const reloadDialogPromise = page.waitForEvent('dialog', { timeout: 5_000 });
  const reloadPromise = page.reload().catch(error => error);
  const reloadDialog = await reloadDialogPromise;
  assert.equal(reloadDialog.type(), 'beforeunload');
  await reloadDialog.dismiss();
  await reloadPromise;
  assert.equal(await page.locator('#flow-input').inputValue(), 'Keep this unsaved flow', 'Dismissing the browser prompt preserves typed content.');
  await page.locator('#flow-input').fill('');
  await page.locator('#technical-details summary').click();
  await page.locator('#suite-editor').fill('{"id":"manual-draft"}');
  assert.equal(await hasBeforeUnloadWarning(), true, 'Pasted manual JSON warns before leaving.');
  await page.locator('#suite-editor').fill('');
  assert.equal(await hasBeforeUnloadWarning(), false, 'Clearing the unsaved content restores the clean state.');
  await page.locator('#technical-details summary').click();
  await page.locator('[data-view="library"]').click();
  await page.locator('#library-list button').first().click();
  await page.locator('#draft-summary .case-review').first().waitFor();
  const flow = await page.locator('#flow-input').inputValue();
  const suite = await page.locator('#suite-editor').inputValue();
  assert.equal(await hasBeforeUnloadWarning(), false, 'An unchanged source-bound suite is clean.');
  assert.equal(await page.locator('#suite-download').isEnabled(), true, 'Saved cases can be downloaded before choosing a target or confirming review.');
  assert.equal(await page.locator('#flow-download').isEnabled(), true);
  await page.locator('#target-select').selectOption('demo');
  await page.locator('#review-checkbox').check();
  assert.equal(await page.locator('#run-btn').isEnabled(), true);

  await page.locator('[data-view="settings"]').click();
  await page.locator('#target-form [name="name"]').fill('unsaved-target');
  await page.locator('#target-form [name="description"]').fill('Keep 사용자 입력 <b>literal</b>');
  const modelInput = page.locator('#model-forms [name="model"]').first();
  await modelInput.fill('unsaved-model');
  const tab = await context.newPage();
  await tab.goto(ui.url);
  await page.locator('#language-select').selectOption('ko');
  await tab.waitForFunction(() => document.documentElement.lang === 'ko');
  assert.equal(await page.locator('html').getAttribute('lang'), 'ko');
  assert.equal(await page.locator('#target-form [name="name"]').inputValue(), 'unsaved-target');
  assert.equal(await page.locator('#target-form [name="description"]').inputValue(), 'Keep 사용자 입력 <b>literal</b>');
  assert.equal(await modelInput.inputValue(), 'unsaved-model');
  assert.equal(await page.locator('#flow-input').inputValue(), flow);
  assert.equal(await page.locator('#suite-editor').inputValue(), suite);
  assert.equal(await page.locator('#review-checkbox').isChecked(), true);
  assert.equal(await page.locator('#target-select').inputValue(), 'demo');
  await page.screenshot({ path: path.join(artifacts, 'settings-ko.png'), fullPage: true });
  await tab.reload();
  assert.equal(await tab.locator('html').getAttribute('lang'), 'ko', 'Saved locale survives reload.');
  await page.locator('#language-select').selectOption('en');
  await tab.waitForFunction(() => document.documentElement.lang === 'en');
  await tab.close();
  await page.locator('[data-view="scenario"]').click();
  await page.screenshot({ path: path.join(artifacts, 'scenario-en.png'), fullPage: true });
  await page.locator('#run-btn').click();
  await page.locator('#language-select').selectOption('ko');
  let state;
  const deadline = Date.now() + 90_000;
  do {
    await new Promise(resolve => setTimeout(resolve, 400));
    state = await (await fetch(ui.url + '/api/state')).json();
  } while ((state.active || !state.lastRunId) && Date.now() < deadline);
  assert.equal(state.active, null);
  assert.ok(state.lastRunId, 'Changing locale must not cancel the actual run.');
  const report = JSON.parse(await readFile(path.join(workspace, '.flowqa/runs', state.lastRunId, 'qa-report.json'), 'utf8'));
  assert.equal(report.status, 'passed');
  assert.equal(report.cases.filter(item => item.status === 'passed').length, 3);
  await page.locator('[data-view="history"]').click();
  await page.locator('#history-list button').first().click();
  await page.locator('#report-content .case-report').first().waitFor();
  await page.screenshot({ path: path.join(artifacts, 'report-ko.png'), fullPage: true });
  const downloadReport = async () => {
    const event = page.waitForEvent('download');
    await page.locator('#report-md').click();
    const download = await event;
    return readFile(await download.path(), 'utf8');
  };
  assert.match(await downloadReport(), /^# QA 결과:/);
  await page.locator('#language-select').selectOption('en');
  assert.match(await downloadReport(), /^# QA results:/);
  await page.screenshot({ path: path.join(artifacts, 'report-en.png'), fullPage: true });
  assert.equal(await page.locator('#report-content .case-report').count(), 3);
  await page.setViewportSize({ width: 390, height: 844 });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false, 'English UI must fit the mobile viewport.');
  await page.screenshot({ path: path.join(artifacts, 'mobile-en.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('[data-view="scenario"]').click();
  assert.equal(await page.locator('#import-btn').textContent(), 'Import case files');
  assert.match(await page.locator('[data-i18n="scenario.importHint"]').textContent(), /one TC JSON/);
  await page.locator('.draft-section').screenshot({ path: path.join(artifacts, 'import-en.png') });
  await page.locator('#language-select').selectOption('ko');
  await page.locator('.draft-section').screenshot({ path: path.join(artifacts, 'import-ko.png') });
  await page.locator('#language-select').selectOption('en');
  const importedFlow = 'Imported source\r\n\r\nKeep trailing spaces  \r\n';
  const importedSuite = { ...JSON.parse(suite), id: 'imported-demo', source: {
    file: 'flows/imported-demo.md', sha256: createHash('sha256').update(importedFlow).digest('hex'),
  } };
  const upload = async (caseFile, markdown = importedFlow) => {
    await page.locator('#import-json').setInputFiles({ name: 'cases.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(caseFile)) });
    await page.locator('#import-markdown').setInputFiles(markdown === null ? [] : { name: 'source.md', mimeType: 'text/markdown', buffer: Buffer.from(markdown) });
    const response = page.waitForResponse((result) => result.url().endsWith('/api/import') && result.request().method() === 'POST');
    await page.locator('#import-btn').click();
    return response;
  };
  const previousSuite = await page.locator('#suite-editor').inputValue();
  const previousFlow = await page.locator('#flow-input').inputValue();
  assert.equal(await page.locator('#review-checkbox').isChecked(), true);
  assert.equal((await upload({ ...importedSuite, schemaVersion: 'wrong' })).status(), 400);
  await page.locator('#notice.notice.error').waitFor();
  assert.equal(await page.locator('#suite-editor').inputValue(), previousSuite);
  assert.equal(await page.locator('#flow-input').inputValue(), previousFlow);
  assert.equal(await page.locator('#review-checkbox').isChecked(), true);
  assert.equal((await upload(importedSuite, 'Changed source\r\n')).status(), 409);
  await page.locator('#notice.notice.error').waitFor();
  assert.equal(await page.locator('#suite-editor').inputValue(), previousSuite);
  assert.equal(await page.locator('#review-checkbox').isChecked(), true);
  assert.equal((await upload(importedSuite)).status(), 200);
  await page.waitForFunction(() => document.querySelector('#draft-source').textContent.includes('imported copy'));
  assert.equal(await page.locator('#flow-input').inputValue(), importedFlow.replaceAll('\r\n', '\n'));
  assert.equal(await page.locator('#review-checkbox').isChecked(), false);
  assert.equal(await page.locator('#run-btn').isEnabled(), false);
  assert.equal(await page.locator('#save-btn').isEnabled(), true);
  assert.equal(JSON.parse(await page.locator('#suite-editor').inputValue()).source, undefined);
  assert.equal(await hasBeforeUnloadWarning(), true, 'An imported draft warns before it is saved.');
  assert.equal(await page.locator('#suite-download').isEnabled(), false, 'Unsaved imported cases cannot be exported as saved files.');
  assert.equal(await page.locator('#flow-download').isEnabled(), false);
  await page.locator('#save-btn').click();
  await page.waitForFunction(() => document.querySelector('#draft-source').textContent.includes('saved cases'));
  assert.equal(await hasBeforeUnloadWarning(), false, 'Saving an imported CRLF flow clears the warning.');
  const savedCopy = JSON.parse(await page.locator('#suite-editor').inputValue());
  assert.match(savedCopy.source.file, /^flows\//);
  assert.equal(await readFile(path.join(workspace, savedCopy.source.file), 'utf8'), importedFlow);
  assert.equal(savedCopy.source.sha256, createHash('sha256').update(importedFlow).digest('hex'));
  const exportedJson = await downloadCaseFile('#suite-download');
  const exportedFlow = await downloadCaseFile('#flow-download');
  assert.match(exportedJson.name, /^imported-demo-[0-9a-f-]+\.json$/);
  assert.equal(exportedFlow.name, path.basename(savedCopy.source.file));
  assert.deepEqual(JSON.parse(exportedJson.text), savedCopy);
  assert.equal(exportedFlow.text, importedFlow, 'Markdown download preserves CRLF and trailing spaces exactly.');
  assert.equal(createHash('sha256').update(exportedFlow.text).digest('hex'), savedCopy.source.sha256);
  assert.equal(await hasBeforeUnloadWarning(), false, 'Downloading does not modify the saved draft.');
  assert.equal(await page.locator('#run-btn').isEnabled(), false);
  await page.locator('#review-checkbox').check();
  assert.equal(await page.locator('#run-btn').isEnabled(), true);
  await page.locator('#language-select').selectOption('ko');
  assert.equal(await page.locator('#import-btn').textContent(), '케이스 파일 가져오기');
  assert.equal(await page.locator('#suite-download').textContent(), '케이스 JSON 다운로드');
  assert.equal(await page.locator('#flow-download').textContent(), '원본 Markdown 다운로드');
  assert.match(await page.locator('[data-i18n="scenario.importHint"]').textContent(), /TC JSON 1개/);
  await page.locator('#language-select').selectOption('en');
  assert.equal((await upload(JSON.parse(exportedJson.text), exportedFlow.text)).status(), 200, 'Downloaded files can be imported together again.');
  await page.waitForFunction(() => document.querySelector('#draft-source').textContent.includes('imported copy'));
  assert.deepEqual(JSON.parse(await page.locator('#suite-editor').inputValue()).cases, savedCopy.cases);
  assert.equal(await page.locator('#review-checkbox').isChecked(), false);
  assert.equal(await page.locator('#run-btn').isEnabled(), false);
  const sourceLessSuite = { ...importedSuite, id: 'imported-no-source' };
  delete sourceLessSuite.source;
  assert.equal((await upload(sourceLessSuite, null)).status(), 200);
  await page.waitForFunction(() => document.querySelector('#draft-source').textContent.includes('imported case copy'));
  assert.equal(await hasBeforeUnloadWarning(), true, 'An imported source-less draft warns before it is saved.');
  assert.equal(await page.locator('#flow-input').inputValue(), '');
  assert.equal(await page.locator('#review-checkbox').isChecked(), false);
  assert.equal(await page.locator('#run-btn').isEnabled(), false);
  assert.equal(JSON.parse(await page.locator('#suite-editor').inputValue()).source, undefined);
  await page.locator('#technical-details summary').click();
  await page.locator('#compile-btn').click();
  await page.waitForFunction(() => document.querySelector('#notice').textContent.includes('JSON validated'));
  await page.locator('#technical-details summary').click();
  await page.locator('#save-btn').click();
  await page.waitForFunction(() => document.querySelector('#draft-source').textContent.includes('saved cases'));
  const savedSourceLess = JSON.parse(await page.locator('#suite-editor').inputValue());
  assert.equal(savedSourceLess.source, undefined);
  assert.equal(await hasBeforeUnloadWarning(), false, 'An unchanged saved source-less suite is clean.');
  assert.equal(await page.locator('#run-btn').isEnabled(), false);
  assert.equal(await page.locator('#suite-download').isEnabled(), true);
  assert.equal(await page.locator('#flow-download').isEnabled(), false, 'Source-less cases offer JSON only.');
  assert.deepEqual(JSON.parse((await downloadCaseFile('#suite-download')).text), savedSourceLess);
  const cleanSourceLessFlow = await page.locator('#flow-input').inputValue();
  await page.locator('#flow-input').fill('Typed flow without a bound source');
  assert.equal(await hasBeforeUnloadWarning(), true, 'Typing a flow for a saved source-less suite warns.');
  assert.equal(await page.locator('#suite-download').isEnabled(), false, 'Unsaved source-less scenario edits disable downloads immediately.');
  await page.locator('#flow-input').fill(cleanSourceLessFlow);
  assert.equal(await hasBeforeUnloadWarning(), false, 'Reverting the source-less flow restores the clean state.');
  assert.equal(await page.locator('#suite-download').isEnabled(), true);
  const cleanSourceLessPlatform = await page.locator('#scenario-platform').inputValue();
  await page.locator('#scenario-platform').selectOption(cleanSourceLessPlatform === 'web' ? 'mobile' : 'web');
  assert.equal(await hasBeforeUnloadWarning(), true, 'Changing the saved suite platform warns before leaving.');
  assert.equal(await page.locator('#suite-download').isEnabled(), false, 'A stale draft cannot be downloaded.');
  await page.locator('#scenario-platform').selectOption(cleanSourceLessPlatform);
  assert.equal(await hasBeforeUnloadWarning(), false, 'Reverting the saved suite platform restores the clean state.');
  await page.locator('#technical-details summary').click();
  await page.locator('#suite-editor').fill(JSON.stringify({ ...savedSourceLess, title: 'Edited source-less suite' }, null, 2));
  assert.equal(await hasBeforeUnloadWarning(), true, 'Editing saved suite JSON warns before leaving.');
  assert.equal(await page.locator('#suite-download').isEnabled(), false);
  const beforeMissingSource = await page.locator('#suite-editor').inputValue();
  assert.equal((await upload(importedSuite, null)).status(), 400);
  await page.locator('#notice.notice.error').waitFor();
  assert.equal(await page.locator('#suite-editor').inputValue(), beforeMissingSource);
  assert.equal(await page.locator('#review-checkbox').isChecked(), false);
  assert.equal(await page.locator('#import-json').evaluate((input) => input.files.length), 1);
  await page.locator('#import-markdown').setInputFiles({ name: 'source.md', mimeType: 'text/markdown', buffer: Buffer.from(importedFlow) });
  const retry = page.waitForResponse((response) => response.url().endsWith('/api/import') && response.request().method() === 'POST');
  await page.locator('#import-btn').click();
  assert.equal((await retry).status(), 200);
  await page.waitForFunction(() => document.querySelector('#draft-source').textContent.includes('imported copy'));
  assert.equal(await page.locator('#import-json').evaluate((input) => input.files.length), 0);
  assert.equal(await page.locator('#import-markdown').evaluate((input) => input.files.length), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Import UI must fit the mobile viewport.');
  assert.deepEqual(errors, [], 'No browser runtime errors.');
  const evidence = { defaultLanguage: 'en', languages: ['en', 'ko'], persistence: true, crossTab: true, userInputPreserved: true, unsavedDraftWarning: true, savedCaseDownloads: true, downloadedCasesReimport: true, reviewPreserved: true, reportDownloadLocale: true, realBrowserCases: 3, status: report.status, importValidation: true, importFlowBytesPreserved: true, importReviewGate: true, mobileOverflow: false, modelCalls: 0 };
  await writeFile(path.join(artifacts, 'result.json'), JSON.stringify(evidence, null, 2) + '\n');
  console.log(JSON.stringify(evidence, null, 2));
} finally {
  await browser?.close(); await ui?.close(); await demo?.close();
  await rm(workspace, { recursive: true, force: true });
}

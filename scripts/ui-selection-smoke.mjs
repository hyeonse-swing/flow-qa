import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { startDemo } from '../examples/demo/server.ts';
import { startUIServer } from '../src/ui/server.ts';
import { initWorkspace, sha256, writeJSON } from '../src/workspace.ts';

const workspace = await mkdtemp(path.join(tmpdir(), 'flowqa-selection-'));
const artifacts = path.resolve('output/playwright/selection');
await mkdir(artifacts, { recursive: true });
let ui; let demo; let browser;
try {
  await initWorkspace(workspace);
  const source = JSON.parse(await readFile(path.join(workspace, 'cases/task-flow.json'), 'utf8'));
  source.id = 'selection-smoke'; source.title = 'Selective run smoke';
  source.cases.push({ ...source.cases[0], id: 'EXCLUDED', title: 'Excluded request sentinel', steps: [
    { type: 'open', path: '/excluded-case-sentinel' },
    { type: 'assertVisible', locator: { by: 'text', value: 'Simple task list' } },
  ] });
  source.cases.push({ ...source.cases[0], id: 'BLOCKED', title: 'Question requires review', questions: ['Which test account?'] });
  const suiteFile = path.join(workspace, 'cases/selection.json');
  await writeJSON(suiteFile, source);
  const originalBytes = await readFile(suiteFile, 'utf8');
  demo = await startDemo(0);
  let excludedRequests = 0;
  demo.server.on('request', req => { if (req.url === '/excluded-case-sentinel') excludedRequests++; });
  await writeJSON(path.join(workspace, 'flowqa.config.json'), { schemaVersion: 'flow-qa/config-1', targets: { demo: { url: demo.url } }, timeoutMs: 15_000, retries: 0 });
  ui = await startUIServer({ workspace, port: 0 });
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(ui.url);
  await page.waitForFunction(() => document.querySelector('#connection-label').textContent.includes('connected'));
  await page.locator('[data-view="library"]').click();
  await page.locator('#library-list .list-row').filter({ hasText: 'Selective run smoke' }).getByRole('button').click();
  await page.waitForFunction(() => document.querySelectorAll('#case-selection-list input:checked').length === 5);
  await page.locator('#target-select').selectOption('demo');
  const input = id => page.locator(`#case-selection-list input[data-case-id="${id}"]`);
  const selected = () => page.locator('#case-selection-list input:checked').evaluateAll(inputs => inputs.map(input => input.dataset.caseId));
  const draft = await page.locator('#suite-editor').inputValue();
  await page.locator('#review-checkbox').check();
  await page.locator('#clear-case-selection').click();
  assert.equal(await page.locator('#review-checkbox').isChecked(), false);
  assert.equal(await page.locator('#run-btn').isEnabled(), false);
  await input('TC-001').check();
  await page.locator('#review-checkbox').check();
  await input('TC-002').check();
  assert.equal(await page.locator('#review-checkbox').isChecked(), false, 'Changing selection requires fresh review.');
  assert.deepEqual(await selected(), ['TC-001', 'TC-002']);
  assert.match(await page.locator('#case-selection-summary').textContent(), /2.*5|5.*2/);
  await page.locator('#language-select').selectOption('ko');
  assert.deepEqual(await selected(), ['TC-001', 'TC-002']);
  await page.locator('[data-view="history"]').click();
  await page.locator('[data-view="scenario"]').click();
  assert.deepEqual(await selected(), ['TC-001', 'TC-002']);
  const refreshResponse = page.waitForResponse(response => response.url().endsWith('/api/state'));
  await page.locator('#reconnect-btn').click();
  await refreshResponse;
  assert.deepEqual(await selected(), ['TC-001', 'TC-002'], 'Settings refresh does not reset selection.');
  assert.equal(await page.locator('#suite-editor').inputValue(), draft);
  assert.equal(await page.evaluate(() => { const e = new Event('beforeunload', {cancelable:true}); window.dispatchEvent(e); return e.defaultPrevented; }), false, 'Selection is not an unsaved draft edit.');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('.execution-section').screenshot({ path: path.join(artifacts, 'selection-ko-mobile.png') });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('#review-checkbox').check();
  const requestPromise = page.waitForRequest(request => request.url().endsWith('/api/run') && request.method() === 'POST');
  const acceptedPromise = page.waitForResponse(response => response.url().endsWith('/api/run') && response.request().method() === 'POST');
  await page.locator('#run-btn').click();
  assert.deepEqual((await requestPromise).postDataJSON().caseIds, ['TC-001', 'TC-002']);
  assert.equal((await acceptedPromise).status(), 202);
  await page.waitForFunction(() => document.querySelector('#case-selection-list input').disabled);
  assert.equal(await page.locator('#select-all-cases').isEnabled(), false);
  assert.equal(await page.locator('#clear-case-selection').isEnabled(), false);
  const waitRun = async () => {
    const deadline = Date.now() + 90_000;
    let state;
    do { await new Promise(resolve => setTimeout(resolve, 200)); state = await (await fetch(ui.url + '/api/state')).json(); } while (state.active && Date.now() < deadline);
    assert.equal(state.active, null, 'Selected run completes.');
    assert.ok(state.lastRunId, state.lastError);
    return (await (await fetch(`${ui.url}/api/report?runId=${state.lastRunId}`)).json()).report;
  };
  const report = await waitRun();
  assert.equal(report.status, 'passed', JSON.stringify(report.errors));
  assert.deepEqual(report.selection, { caseIds: ['TC-001', 'TC-002'], totalCases: 5 });
  assert.deepEqual(report.cases.map(item => item.id), ['TC-001', 'TC-002']);
  assert.equal(excludedRequests, 0, 'The unselected sentinel case never made its request.');
  assert.equal(await readFile(suiteFile, 'utf8'), originalBytes);
  const snapshot = await readFile(path.join(workspace, '.flowqa/runs', report.runId, 'suite.json'), 'utf8');
  assert.equal(JSON.parse(snapshot).cases.length, 5);
  assert.equal(report.suiteHash, sha256(snapshot));
  const compiled = await readFile(path.join(workspace, '.flowqa/runs', report.runId, 'suite.e2e.ts'), 'utf8');
  assert.doesNotMatch(compiled, /EXCLUDED|BLOCKED|TC-003/);
  await page.locator('[data-view="history"]').click();
  await page.waitForFunction(id => document.querySelector('#history-list').textContent.includes(id), report.runId);
  assert.match(await page.locator('#history-list').textContent(), /2.*5|5.*2/);
  await page.locator('#history-list .list-row').filter({ hasText: report.runId }).getByRole('button').click();
  await page.locator('#report-content .case-report').first().waitFor();
  assert.equal(await page.locator('#report-content .case-report').count(), 2);
  assert.match(await page.locator('#report-content').textContent(), /2.*5|5.*2/);
  const downloadMarkdown = async () => {
    const pending = page.waitForEvent('download'); await page.locator('#report-md').click();
    return readFile(await (await pending).path(), 'utf8');
  };
  assert.match(await downloadMarkdown(), /선택|부분/);
  await page.locator('#language-select').selectOption('en');
  assert.match(await downloadMarkdown(), /[Ss]elected|[Pp]artial/);
  await page.locator('[data-view="scenario"]').click();
  await page.waitForFunction(() => !document.querySelector('#select-all-cases').disabled);
  await page.locator('#select-all-cases').click();
  assert.equal(await page.locator('#review-checkbox').isChecked(), false);
  assert.equal((await selected()).length, 5);
  // A second run selects only a blocked case. It must not execute any browser step.
  await page.locator('#clear-case-selection').click();
  await input('BLOCKED').check();
  await page.locator('#review-checkbox').check();
  const blockedAccepted = page.waitForResponse(response => response.url().endsWith('/api/run') && response.request().method() === 'POST');
  await page.locator('#run-btn').click();
  assert.equal((await blockedAccepted).status(), 202);
  const blocked = await waitRun();
  assert.equal(blocked.status, 'blocked');
  assert.deepEqual(blocked.selection, {caseIds:['BLOCKED'],totalCases:5});
  assert.equal(blocked.cases.length, 1);
  assert.equal(blocked.cases[0].attempts.length, 0);
  assert.equal(excludedRequests, 0);
  await page.locator('[data-view="history"]').click();
  await page.waitForFunction(id => [...document.querySelector('#compare-current').options].some(option => option.value === id), blocked.runId);
  await page.locator('#compare-baseline').selectOption(report.runId);
  await page.locator('#compare-current').selectOption(blocked.runId);
  await page.locator('#compare-btn').click();
  await page.waitForFunction(() => !document.querySelector('#comparison-json').disabled);
  const compared = await (await fetch(`${ui.url}/api/comparison?baseline=${report.runId}&current=${blocked.runId}`)).json();
  assert.ok(compared.comparison.warnings.includes('partial-run'));
  assert.ok(compared.comparison.warnings.includes('selection-changed'));
  assert.equal(compared.comparison.counts.missing, 2);
  assert.equal(compared.comparison.counts.added, 1);
  assert.equal(compared.comparison.counts['now-passed'], 0);
  assert.match(await page.locator('#comparison-warnings').textContent(), /selected|partial|selection/i);
  await page.screenshot({ path: path.join(artifacts, 'selected-comparison-en.png'), fullPage: true });
  assert.deepEqual(errors, []);
  const result = { selectedExecution: true, realBrowserCases: 2, unselectedRequests: excludedRequests, selectedBlockedCases: 1, fullSnapshotPreserved: true, scopeInReportsAndComparison: true, reviewInvalidated: true, bilingual: true, mobileOverflow: false, modelCalls: 0 };
  await writeFile(path.join(artifacts, 'result.json'), JSON.stringify(result, null, 2) + '\n');
  console.log(JSON.stringify(result, null, 2));
} finally {
  if (browser) await browser.close();
  if (ui) await ui.close();
  if (demo) await demo.close();
  await rm(workspace, { recursive: true, force: true });
}
